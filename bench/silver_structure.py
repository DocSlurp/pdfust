from typing import Any, Literal

from bench.silver import ARTIFACTS, canonical, guard_path, load_manifest, rss_bytes, sha, verify_input, write_json

ROOT = Path(__file__).resolve().parents[1]
TABLE_FAMILIES = {"merged-table", "multilevel-table"}
LABEL = "repository-authored silver; not independently reviewed"
STRATEGIES: tuple[Literal["lines", "text"], ...] = ("lines", "text")


def process_peak_rss() -> tuple[int | None, str]:
    """Measure current-exec Linux RSS, avoiding inherited pre-exec rusage peaks."""
    try:
        for line in Path("/proc/self/status").read_text().splitlines():
            if line.startswith("VmHWM:"):
                return int(line.split()[1]) * 1024, "/proc/self/status VmHWM (current executable)"
    except (OSError, ValueError):
        pass
    return rss_bytes(), "getrusage(RUSAGE_SELF).ru_maxrss (may include pre-exec launcher memory)"


def authored_table(variant: int) -> dict[str, Any]:
    """Transcribe the explicit classic-layout rules and labels into display space.

    Both table families draw x=[40,200,365,550], PDF y=[680,645,610,
    575,540,505]. The x=200 divider stops at645, merging the first two
    top-row slots. Labels shift by3*variant; rules remain fixed.
    """
    rows: list[list[str | None]] = [["Regional totals", None, "Year"], ["East", "West", "Combined"]]
    rows.extend([[f"R{row + 1}C{col + 1} {10 * (row + 1) + col + variant}" for col in range(3)] for row in range(3)])
    xs = [40, 200, 365, 550]
    ys = [112, 147, 182, 217, 252, 287]
    cells: list[list[int] | None] = []
    spans = []
    for row, values in enumerate(rows):
        for col, value in enumerate(values):
            if value is None:
                cells.append(None)
                continue
            width = 2 if row == 0 and col == 0 else 1
            cells.append([xs[col], ys[row], xs[col + width], ys[row + 1]])
            spans.append({"row": row, "column": col, "row_span": 1, "column_span": width})
    return {"bbox": [40, 112, 550, 287], "row_count": 5, "col_count": 3, "values": rows, "cells": cells, "spans": spans}


def prepare_targets(directory: Path) -> dict[str, Any]:
    """Prepare private all-page targets after verifying exact generated DEV inputs.

    No references are supplied to a model. Non-table layouts and every math
    encoding target zero tables. This tests table detection only; it does not
    score general layout, form semantics, prose reading order, or formulas.
    """
    from bench.silver_layouts import generate_cases as layouts
    from bench.silver_math import generate_cases as math_cases

    directory = guard_path(directory)
    manifest = load_manifest(directory)
    generated: dict[str, Any] = {case["id"]: case for case in layouts() + math_cases()}
    if set(generated) != {case["id"] for case in manifest["cases"]}:
        raise ValueError("Structural references require the complete matching generated DEV dataset")
    targets = []
    for record in manifest["cases"]:
        source = generated[record["id"]]
        if record["pdf_sha256"] != sha(source["pdf"]):
            raise ValueError("Generated bytes no longer match frozen structural inputs")
        for field in ("family", "encoding", "producer_group", "page_count"):
            if record.get(field) != source.get(field):
                raise ValueError("Manifest metadata differs from authored generator")
        verify_input(directory, record)
        page_count = int(source.get("page_count", 1))
        family = source["family"]
        variant = int(source["id"].rsplit("-v", 1)[1]) - 1 if family in TABLE_FAMILIES else None
        for page_number in range(page_count):
            tables = [authored_table(variant)] if variant is not None else []
            targets.append(
                {
                    "id": record["id"],
                    "page_number": page_number,
                    "family": family,
                    "encoding": source["encoding"],
                    "pdf_sha256": record["pdf_sha256"],
                    "split": "DEV",
                    "label_status": LABEL,
                    "tables": tables,
                }
            )
    return {
        "schema": 1,
        "dataset_sha256": manifest["dataset_sha256"],
        "split": "DEV",
        "label_status": LABEL,
        "reference_source": "silver_layouts._content authored geometry and labels",
        "scope": "bordered table structure and non-table false positives only",
        "pages": targets,
    }


def observed_table(table: Any) -> dict[str, Any]:
    """Retain public detected geometry, cell text and diagnostics without reference access."""
    cells = [list(cell) if cell is not None else None for cell in table.cells]
    # Rule-derived grids expose boundaries through their cells. Text candidates
    # can have gaps; their independent edge topology remains observable here.
    xs = sorted({round(cell[x], 3) for cell in cells if cell is not None for x in (0, 2)})
    ys = sorted({round(cell[y], 3) for cell in cells if cell is not None for y in (1, 3)})
    spans = []
    for index, cell in enumerate(cells):
        if cell is None:
            continue
        spans.append(
            {
                "row": index // table.col_count,
                "column": index % table.col_count,
                "row_span": ys.index(round(cell[3], 3)) - ys.index(round(cell[1], 3)),
                "column_span": xs.index(round(cell[2], 3)) - xs.index(round(cell[0], 3)),
            }
        )
    return {
        "bbox": list(table.bbox),
        "row_count": table.row_count,
        "col_count": table.col_count,
        "values": table.extract(),
        "cells": cells,
        "spans": spans,
        "diagnostics": dict(table.diagnostics._asdict()),
    }


def normalized(value: str | None) -> str | None:
    """Ignore inferred whitespace only; retain every authored value and label."""
    return " ".join(value.split()) if value is not None else None


def score_page(target: dict[str, Any], observed: list[dict[str, Any]]) -> dict[str, Any]:
    """Score authored ownership and complete grid exactness, never detector confidence."""
    gold = target["tables"]
    if not gold:
        return {
            "expected_tables": 0,
            "detected_tables": len(observed),
            "false_positive_page": bool(observed),
            "false_positive_tables": len(observed),
            "exact_page": not observed,
            "correct_cell_slots": 0,
            "cell_slots": 0,
            "correct_owned_values": 0,
            "owned_values": 0,
            "exact_spans": None,
            "exact_cells": None,
        }
    expected = gold[0]
    flat_expected = [normalized(value) for row in expected["values"] for value in row]
    owned = [value for value in flat_expected if value is not None]
    all_values = [normalized(value) for table in observed for row in table["values"] for value in row]
    candidates = [
        table
        for table in observed
        if table["row_count"] == expected["row_count"] and table["col_count"] == expected["col_count"]
    ]
    actual = next(
        (
            table
            for table in candidates
            if all(abs(a - b) <= 0.5 for a, b in zip(table["bbox"], expected["bbox"], strict=True))
        ),
        None,
    )
    flat_actual = [normalized(value) for row in actual["values"] for value in row] if actual else []
    correct = sum(a == b for a, b in zip(flat_expected, flat_actual, strict=False))
    ownership = sum(
        value is not None and index < len(flat_actual) and flat_actual[index] == value and all_values.count(value) == 1
        for index, value in enumerate(flat_expected)
    )
    exact_cells = flat_actual == flat_expected
    exact_spans = actual is not None and actual["spans"] == expected["spans"]
    return {
        "expected_tables": 1,
        "detected_tables": len(observed),
        "false_positive_page": False,
        "false_positive_tables": max(0, len(observed) - int(actual is not None)),
        "exact_page": len(observed) == 1 and exact_cells and exact_spans,
        "correct_cell_slots": correct,
        "cell_slots": len(flat_expected),
        "correct_owned_values": ownership,
        "owned_values": len(owned),
        "exact_cells": exact_cells,
        "exact_spans": exact_spans,
    }


def run(directory: Path, *, summary_path: Path = ROOT / "bench/results/silver-structure.md") -> dict[str, Any]:
    """Measure all DEV pages on CPU and retain complete local targets and detections."""
    import pdfust

    directory = guard_path(directory)
    targets = prepare_targets(directory)
    target_map = {(page["id"], page["page_number"]): page for page in targets["pages"]}
    manifest = load_manifest(directory)
    runs = directory / "structure-runs"
    runs.mkdir(exist_ok=True)
    output = Path(mkdtemp(prefix=time.strftime("%Y%m%dT%H%M%S-", time.gmtime()), dir=runs))
    write_json(output / "targets.json", targets)
    rows = []
    start, cpu = time.perf_counter(), time.process_time()
    before = os.times()
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        for record in manifest["cases"]:
            path = verify_input(directory, record)
            with pdfust.open(path) as document:
                expected_pages = sum(target["id"] == record["id"] for target in targets["pages"])
                if len(document) != expected_pages:
                    raise ValueError("PDF page count differs from authored targets")
                for page_number, page in enumerate(document):
                    target = target_map[(record["id"], page_number)]
                    for strategy in STRATEGIES:
                        began, began_cpu = time.perf_counter(), time.process_time()
                        row: dict[str, Any] = {
                            "id": record["id"],
                            "page_number": page_number,
                            "family": target["family"],
                            "strategy": strategy,
                        }
                        try:
                            observed = [observed_table(table) for table in page.find_tables(strategy=strategy).tables]
                            row.update(status="ok", observed=observed, scores=score_page(target, observed))
                        except Exception as exc:
                            row.update(status="error", error_type=type(exc).__name__, error=str(exc))
                        row.update(
                            wall_ms=(time.perf_counter() - began) * 1000,
                            cpu_ms=(time.process_time() - began_cpu) * 1000,
                        )
                        rows.append(row)
    elapsed, cpu_seconds = time.perf_counter() - start, time.process_time() - cpu
    after = os.times()
    peak_rss, rss_tool = process_peak_rss()
    resources = {
        "wall_seconds": elapsed,
        "cpu_seconds": cpu_seconds,
        "cpu_utilization_pct": 100 * cpu_seconds / elapsed,
        "user_cpu_seconds": after.user - before.user,
        "system_cpu_seconds": after.system - before.system,
        "peak_rss_bytes": peak_rss,
        "workers": 1,
        "scope": "wall/CPU: checksum reads, document load, both sequential strategies, scoring; "
        "excludes imports/target preparation/artifact writes. Peak RSS: full runner lifetime.",
        "tool": "perf_counter/process_time/os.times; " + rss_tool,
        "sampling_interval": "OS cumulative counters and high-water RSS; no periodic sampling",
        "platform": platform.platform(),
        "python": platform.python_version(),
        "logical_cpus": os.cpu_count(),
    }
    totals = {}
    for strategy in STRATEGIES:
        selected = [row for row in rows if row["strategy"] == strategy and row["status"] == "ok"]
        scores = [row["scores"] for row in selected]
        totals[strategy] = {
            "completed_pages": len(selected),
            "errors": len(targets["pages"]) - len(selected),
            **{
                key: sum(score[key] for score in scores)
                for key in (
                    "expected_tables",
                    "detected_tables",
                    "false_positive_tables",
                    "false_positive_page",
                    "exact_page",
                    "correct_cell_slots",
                    "cell_slots",
                    "correct_owned_values",
                    "owned_values",
                )
            },
            "exact_table_cells": sum(score["exact_cells"] is True for score in scores),
            "exact_table_spans": sum(score["exact_spans"] is True for score in scores),
        }
    for result in totals.values():
        result["expected_tables"] = sum(len(page["tables"]) for page in targets["pages"])
        result["cell_slots"] = sum(
            table["row_count"] * table["col_count"] for page in targets["pages"] for table in page["tables"]
        )
        result["owned_values"] = sum(
            value is not None
            for page in targets["pages"]
            for table in page["tables"]
            for row in table["values"]
            for value in row
        )
    negative_pages = sum(not page["tables"] for page in targets["pages"])
    artifact_location = output.relative_to(ROOT) if output.is_relative_to(ROOT) else output
    summary = {
        "schema": 1,
        "dataset_sha256": targets["dataset_sha256"],
        "split": "DEV",
        "label_status": LABEL,
        "documents": len(manifest["cases"]),
        "pages": len(targets["pages"]),
        "totals": totals,
        "resources": resources,
        "run_directory": str(output),
        "warnings": sorted({str(w.message) for w in caught}),
        "runner_sha256": sha(Path(__file__).read_bytes()),
    }
    write_json(output / "summary.json", summary)
    with (output / "pages.jsonl").open("w") as handle:
        for row in rows:
            handle.write(canonical(row).decode() + "\n")
    text = [
        "# Authored silver table structure baseline",
        "",
        f"{summary['documents']} DEV documents, {summary['pages']} "
        "physical pages. References are transcribed from authored generator geometry and labels, "
        "not extraction output. "
        "They are not independently reviewed gold. Only bordered tables and non-table false positives are scored; "
        "math, form semantics, prose order and full layout quality are outside this score.",
        "",
        "| Strategy | Exact table cells | Exact merged spans | Owned values | Non-table FP pages | "
        "Unmatched tables | Errors |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for strategy, result in totals.items():
        text.append(
            f"| {strategy} | {result['exact_table_cells']}/{result['expected_tables']} | "
            f"{result['exact_table_spans']}/{result['expected_tables']} | "
            f"{result['correct_owned_values']}/{result['owned_values']} | "
            f"{result['false_positive_page']}/{negative_pages} | "
            f"{result['false_positive_tables']} | {result['errors']} |"
        )
    text += [
        "",
        "Exact cells include every row-major slot and the covered `None` slot. Span topology is measured "
        "separately. Ownership requires the complete authored cell value in its intended slot and exactly one "
        "occurrence across detected cells. Decorative rectangles, checkbox fields, prose panels and all math "
        "pages target zero tables. Text-strategy false positives remain counted. Unmatched candidates include "
        "partial grids on authored table pages; they are not exact complete-table recoveries.",
        "",
        f"Sequential CPU run: {elapsed:.3f}s wall, {cpu_seconds:.3f}s CPU ({resources['cpu_utilization_pct']:.1f}% "
        f"of one core); peak RSS {resources['peak_rss_bytes']} bytes. {resources['scope']} "
        f"Tool: {resources['tool']}. Sampling: {resources['sampling_interval']}. "
        f"Machine: {resources['platform']}; Python {resources['python']}; {resources['logical_cpus']} logical CPUs; "
        "one worker. Strategy timings share a document and may reuse interpretation caches; these are not cold "
        "independent performance comparisons.",
        "",
        f"Dataset SHA-256: `{targets['dataset_sha256']}`. Complete private "
        "targets, every detected table and per-page scores/resources are retained in the ignored "
        f"`{artifact_location}` directory. No hosted models or model calls were used.",
        "",
    ]
    summary_path.write_text("\n".join(text))
    return summary


def main() -> None:
    """Prepare and run one complete local structural baseline."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--directory", type=Path)
    args = parser.parse_args()
    directory = args.directory or Path(json.loads(guard_path(ARTIFACTS / "latest.json").read_text())["path"])
    print(json.dumps(run(directory), indent=2))


if __name__ == "__main__":
    main()
