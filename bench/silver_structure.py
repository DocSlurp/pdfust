"""Offline authored-silver table structure baseline for the complete DEV pages.

References come from layout construction, never extractor output. They are
repository-authored silver targets, not independent review or mathematical gold.
"""

# Artifacts retain heterogeneous producer metadata and public table observations.
# ruff: noqa: ANN401, EM101, TRY003, PLC0415, PLR2004, ISC004

from __future__ import annotations

import argparse
import json
import os
import platform
import time
import warnings
from pathlib import Path
